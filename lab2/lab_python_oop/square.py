# Используем прямоугольник как базовый класс: квадрат является его частным случаем.
from .rectangle import Rectangle


# Квадрат наследует расчет площади и метод получения названия фигуры.
class Square(Rectangle):
    # Переопределяем название, чтобы оно отображалось как «Квадрат».
    FIGURE_TYPE = "Квадрат"

    def __init__(self, side, color):
        # Передаем длину стороны как ширину и высоту в конструктор прямоугольника.
        super().__init__(side, side, color)

    def __repr__(self):
        # Показываем одну сторону вместо двух одинаковых размеров.
        # Для расчета площади используется унаследованный метод area().
        return "{}: сторона = {}, цвет = {}, площадь = {}".format(
            self.get_figure_type(),
            self.width,
            self.color.color,
            self.area()
        )
